/* 把图标名拼成完整的 <svg> 字符串;size 可选,不传就用 .ic 的默认 24px */
function ic(name, size){
  return `<svg class="ic" viewBox="0 0 24 24" ${size ? `style="width:${size}px;height:${size}px"` : ''} aria-hidden="true">${IC[name]}</svg>`;
}

/* 扫描 HTML 里所有 <span data-ic="xxx"> 占位符,替换成真正的图标 */
document.querySelectorAll('[data-ic]').forEach(el => el.innerHTML = ic(el.dataset.ic));
